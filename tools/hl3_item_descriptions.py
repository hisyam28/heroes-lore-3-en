METADATA_SIZES={'i13_dat':5,'i14_dat':0,'i16_dat':4,'i17_dat':0,'i18_dat':4}


def wrap(value,width=22):
    return ';'.join(textwrap.wrap(value,width=width,break_long_words=False,break_on_hyphens=False))


def split_tail(tail,filename):
    if len(tail)<5:raise ValueError('Missing item description prefix')
    n=tail[4];end=5+n
    if len(tail)-end!=METADATA_SIZES[filename]:raise ValueError('Unknown item description metadata layout')
    return tail[:4],tail[5:end].decode('cp949'),tail[end:]


def compile_descriptions(original: Path,output: Path):
    entries=[]
    for filename,copy in COPY.items():
        rel='res/dat/'+filename;source=parse((original/rel).read_bytes(),1,rel)
        current=parse((output/rel).read_bytes(),1,rel)
        assert len(source)==len(copy)==len(current)
        result=[]
        for i,((texts,tail),(names,_),value) in enumerate(zip(source,current,copy)):
            price,old,metadata=split_tail(tail,filename);value=wrap(value)
            raw=value.encode('ascii');assert len(raw)<=255 and len(value.split(';'))<=2
            result.append((names,price+bytes([len(raw)])+raw+metadata))
            entries.append({'file':rel,'record':i,'source':old,'translation':value})
        (output/rel).write_bytes(build(result,rel))
    (ROOT/'translations/item-descriptions.json').write_text(json.dumps({'entries':entries},ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    return len(entries)
